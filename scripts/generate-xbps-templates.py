#!/usr/bin/env python3
"""Generate conservative XBPS templates from reviewed release tarballs.

The recipe list is intentionally explicit.  Discovery is automated, but a
package is generated only after its repository, asset pattern, executable and
license have been reviewed and added to meta/tarballs.tsv.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.error
import urllib.parse
import urllib.request
from dataclasses import dataclass
from pathlib import Path, PurePosixPath


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RECIPES = ROOT / "meta" / "tarballs.tsv"
GENERATED_MARKER = "# Generated by scripts/generate-xbps-templates.py; DO NOT EDIT."
DEFAULT_MAINTAINER = "Neko Void Linux <admin@neko-void-linux.online>"
MAX_DOWNLOAD_BYTES = 512 * 1024 * 1024
MAX_UNPACKED_BYTES = 2 * 1024 * 1024 * 1024
MAX_MEMBERS = 50_000

ARCHIVE_SUFFIXES = (
    ".tar.gz",
    ".tgz",
    ".tar.xz",
    ".txz",
    ".tar.bz2",
    ".tbz2",
    ".tar.zst",
    ".tzst",
    ".tar",
)
BAD_SUFFIXES = (
    ".asc",
    ".sig",
    ".sha1",
    ".sha256",
    ".sha512",
    ".md5",
    ".minisig",
    ".sbom",
    ".spdx",
)
BAD_OS_TOKENS = (
    "windows",
    "win32",
    "win64",
    "darwin",
    "macos",
    "osx",
    "freebsd",
    "openbsd",
    "netbsd",
    "dragonfly",
    "android",
    "plan9",
    "solaris",
)
BAD_ARCH_RE = re.compile(
    r"(?:^|[_.-])(aarch64|arm64|armv\d*|armhf|i[3-6]86|386|riscv\d*|"
    r"mips\w*|s390x|ppc\w*)(?:[_.-]|$)",
    re.IGNORECASE,
)
GOOD_ARCH_RE = re.compile(
    r"(?:^|[_.-])(x86_64|amd64|x64|64bit)(?:[_.-]|$)", re.IGNORECASE
)
LICENSE_RE = re.compile(
    r"^(license|licence|copying|copyright|notice)(?:[._-].*)?$", re.IGNORECASE
)


class GeneratorError(RuntimeError):
    pass


@dataclass(frozen=True)
class Recipe:
    pkgname: str
    repo: str
    asset_pattern: str
    kind: str
    executable: str
    build_style: str
    license: str
    short_desc: str
    maintainer: str = DEFAULT_MAINTAINER
    hostmakedepends: str = ""
    makedepends: str = ""
    depends: str = ""
    configure_args: str = ""


@dataclass(frozen=True)
class ReleaseAsset:
    name: str
    url: str
    size: int


@dataclass(frozen=True)
class InspectedArchive:
    executable_path: str | None
    license_path: str | None
    target_arch: str
    source_root: str | None = None


def log(message: str) -> None:
    print(message, file=sys.stderr)


def read_recipes(path: Path) -> list[Recipe]:
    recipes: list[Recipe] = []
    seen: set[str] = set()
    with path.open(encoding="utf-8") as handle:
        for line_number, raw_line in enumerate(handle, 1):
            line = raw_line.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            fields = line.split("\t")
            if len(fields) < 8 or len(fields) > 13:
                raise GeneratorError(
                    f"{path}:{line_number}: se esperaban entre 8 y 13 columnas TSV"
                )
            fields += [""] * (13 - len(fields))
            (
                pkgname,
                repo,
                pattern,
                kind,
                executable,
                build_style,
                license_id,
                desc,
                maintainer,
                hostmakedepends,
                makedepends,
                depends,
                configure_args,
            ) = (field.strip() for field in fields)
            if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9+._-]*", pkgname):
                raise GeneratorError(
                    f"{path}:{line_number}: pkgname invalido: {pkgname!r}"
                )
            repo = normalize_repo(repo)
            if pattern != "TARBALL":
                try:
                    re.compile(pattern, re.IGNORECASE)
                except re.error as exc:
                    raise GeneratorError(
                        f"{path}:{line_number}: patron invalido: {exc}"
                    ) from exc
            if kind not in {"binary", "source"}:
                raise GeneratorError(
                    f"{path}:{line_number}: tipo debe ser binary o source"
                )
            if kind == "binary" and (
                "/" in executable or executable in {"", ".", "..", "-"}
            ):
                raise GeneratorError(
                    f"{path}:{line_number}: binary requiere un executable base"
                )
            if kind == "source" and build_style not in {
                "cmake",
                "meson",
                "gnu-configure",
                "gnu-makefile",
            }:
                raise GeneratorError(
                    f"{path}:{line_number}: build_style source no soportado: {build_style!r}"
                )
            if pattern == "TARBALL" and kind != "source":
                raise GeneratorError(
                    f"{path}:{line_number}: TARBALL solo se admite para recetas source"
                )
            if not license_id:
                raise GeneratorError(f"{path}:{line_number}: falta license SPDX")
            if not desc:
                raise GeneratorError(f"{path}:{line_number}: falta short_desc")
            if pkgname in seen:
                raise GeneratorError(f"{path}:{line_number}: pkgname duplicado: {pkgname}")
            seen.add(pkgname)
            recipes.append(
                Recipe(
                    pkgname=pkgname,
                    repo=repo,
                    asset_pattern=pattern,
                    kind=kind,
                    executable=executable,
                    build_style=build_style,
                    license=license_id,
                    short_desc=desc,
                    maintainer=maintainer or DEFAULT_MAINTAINER,
                    hostmakedepends=hostmakedepends,
                    makedepends=makedepends,
                    depends=depends,
                    configure_args=configure_args,
                )
            )
    return recipes


def normalize_repo(value: str) -> str:
    value = value.strip().rstrip("/")
    value = re.sub(r"^https?://github\.com/", "", value, flags=re.IGNORECASE)
    if value.endswith(".git"):
        value = value[:-4]
    if not re.fullmatch(r"[^/\s]+/[^/\s]+", value):
        raise GeneratorError(f"repositorio GitHub invalido: {value!r}")
    return value


def github_json(url: str, token: str) -> dict:
    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "neko-pkgs-xbps-template-generator",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.load(response)
    except (urllib.error.URLError, json.JSONDecodeError) as exc:
        raise GeneratorError(f"fallo consultando {url}: {exc}") from exc


def latest_release(recipe: Recipe, token: str) -> tuple[str, str, ReleaseAsset]:
    repo_url = f"https://api.github.com/repos/{recipe.repo}"
    release_url = f"{repo_url}/releases/latest"
    repo_data = github_json(repo_url, token)
    release_data = github_json(release_url, token)
    raw_tag = str(release_data.get("tag_name") or "").strip()
    if not raw_tag:
        raise GeneratorError(f"{recipe.pkgname}: la release no tiene tag_name")
    version = raw_tag[1:] if raw_tag.startswith("v") and len(raw_tag) > 1 else raw_tag
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9.+_~-]*", version):
        raise GeneratorError(
            f"{recipe.pkgname}: version no compatible con XBPS: {version!r}"
        )

    if recipe.asset_pattern == "TARBALL":
        repo_name = recipe.repo.rsplit("/", 1)[1]
        asset = ReleaseAsset(
            name=f"{repo_name}-{version}.tar.gz",
            url=f"https://github.com/{recipe.repo}/archive/refs/tags/{raw_tag}.tar.gz",
            size=0,
        )
    else:
        assets: list[ReleaseAsset] = []
        for item in release_data.get("assets") or []:
            name = str(item.get("name") or "")
            url = str(item.get("browser_download_url") or "")
            size = int(item.get("size") or 0)
            if name and url:
                assets.append(ReleaseAsset(name=name, url=url, size=size))
        asset = select_asset(recipe, assets)
    homepage = str(repo_data.get("html_url") or f"https://github.com/{recipe.repo}")
    return version, homepage, asset


def is_compatible_asset_name(name: str, kind: str = "binary") -> bool:
    lower = name.lower()
    if not lower.endswith(ARCHIVE_SUFFIXES):
        return False
    if lower.endswith(BAD_SUFFIXES):
        return False
    if any(token in lower for token in BAD_OS_TOKENS):
        return False
    if BAD_ARCH_RE.search(lower):
        return False
    if kind == "binary":
        if "linux" not in lower:
            return False
        if not GOOD_ARCH_RE.search(lower):
            return False
        if re.search(r"(?:^|[_.-])(source|sources|src)(?:[_.-]|$)", lower):
            return False
    return True


def select_asset(recipe: Recipe, assets: list[ReleaseAsset]) -> ReleaseAsset:
    pattern = re.compile(recipe.asset_pattern, re.IGNORECASE)
    candidates = [
        asset
        for asset in assets
        if pattern.search(asset.name) and is_compatible_asset_name(asset.name, recipe.kind)
    ]
    if not candidates:
        matched = [asset.name for asset in assets if pattern.search(asset.name)]
        suffix = f"; coincidieron pero fueron rechazados: {', '.join(matched)}" if matched else ""
        raise GeneratorError(
            f"{recipe.pkgname}: no hay tarball {recipe.kind} compatible{suffix}"
        )

    def score(asset: ReleaseAsset) -> tuple[int, int, str]:
        lower = asset.name.lower()
        libc_rank = (
            0
            if recipe.kind == "source" or "gnu" in lower or "glibc" in lower
            else 2
            if "musl" in lower
            else 1
        )
        auxiliary = 1 if any(x in lower for x in ("debug", "symbols", "test")) else 0
        return libc_rank, auxiliary, lower

    candidates.sort(key=score)
    best = candidates[0]
    if len(candidates) > 1 and score(candidates[0])[:2] == score(candidates[1])[:2]:
        names = ", ".join(asset.name for asset in candidates)
        raise GeneratorError(
            f"{recipe.pkgname}: patron ambiguo; varios assets equivalentes: {names}"
        )
    return best


def download_asset(asset: ReleaseAsset, destination: Path) -> str:
    if asset.size > MAX_DOWNLOAD_BYTES:
        raise GeneratorError(
            f"{asset.name}: supera el limite de {MAX_DOWNLOAD_BYTES // (1024 * 1024)} MiB"
        )
    request = urllib.request.Request(
        asset.url,
        headers={"User-Agent": "neko-pkgs-xbps-template-generator"},
    )
    digest = hashlib.sha256()
    total = 0
    try:
        with urllib.request.urlopen(request, timeout=60) as response, destination.open("wb") as out:
            while chunk := response.read(1024 * 1024):
                total += len(chunk)
                if total > MAX_DOWNLOAD_BYTES:
                    raise GeneratorError(f"{asset.name}: descarga demasiado grande")
                digest.update(chunk)
                out.write(chunk)
    except urllib.error.URLError as exc:
        raise GeneratorError(f"no se pudo descargar {asset.url}: {exc}") from exc
    if total == 0:
        raise GeneratorError(f"{asset.name}: descarga vacia")
    return digest.hexdigest()


def prepare_tar(asset_path: Path, asset_name: str, temporary_dir: Path) -> Path:
    lower = asset_name.lower()
    if not lower.endswith((".tar.zst", ".tzst")):
        return asset_path
    if not shutil.which("zstd"):
        raise GeneratorError("se necesita zstd para revisar archivos .tar.zst")
    plain_tar = temporary_dir / "archive.tar"
    with plain_tar.open("wb") as output:
        process = subprocess.run(
            ["zstd", "-q", "-d", "-c", str(asset_path)],
            stdout=output,
            stderr=subprocess.PIPE,
            check=False,
        )
    if process.returncode != 0:
        message = process.stderr.decode("utf-8", "replace").strip()
        raise GeneratorError(f"tarball zstd corrupto: {message}")
    return plain_tar


def safe_member_path(name: str) -> PurePosixPath:
    normalized = name[2:] if name.startswith("./") else name
    path = PurePosixPath(normalized)
    if not normalized or path.is_absolute() or ".." in path.parts:
        raise GeneratorError(f"ruta insegura dentro del tarball: {name!r}")
    return path


def validate_link(member: tarfile.TarInfo) -> None:
    target = PurePosixPath(member.linkname)
    if target.is_absolute():
        raise GeneratorError(f"enlace absoluto inseguro: {member.name!r} -> {member.linkname!r}")
    parent = safe_member_path(member.name).parent
    depth = 0
    for part in (parent / target).parts:
        if part in {"", "."}:
            continue
        if part == "..":
            depth -= 1
            if depth < 0:
                raise GeneratorError(
                    f"enlace escapa del tarball: {member.name!r} -> {member.linkname!r}"
                )
        else:
            depth += 1


def inspect_elf(path: Path) -> None:
    header = path.read_bytes()[:64]
    if len(header) < 20 or header[:4] != b"\x7fELF":
        raise GeneratorError(f"el ejecutable principal no es ELF: {path.name}")
    if header[4] != 2:
        raise GeneratorError(f"el ejecutable principal no es ELF de 64 bits: {path.name}")
    byteorder = "little" if header[5] == 1 else "big" if header[5] == 2 else ""
    if not byteorder:
        raise GeneratorError(f"ELF con endian invalido: {path.name}")
    machine = int.from_bytes(header[18:20], byteorder=byteorder)
    if machine != 62:
        raise GeneratorError(
            f"ELF incompatible: e_machine={machine}, se esperaba x86_64 (62)"
        )


def source_build_marker(build_style: str, path: PurePosixPath) -> bool:
    markers = {
        "cmake": {"CMakeLists.txt"},
        "meson": {"meson.build"},
        "gnu-configure": {"configure", "configure.ac", "configure.in"},
        "gnu-makefile": {"Makefile", "GNUmakefile"},
    }
    return path.name in markers[build_style]


def inspect_archive(asset_path: Path, asset_name: str, recipe: Recipe) -> InspectedArchive:
    with tempfile.TemporaryDirectory(prefix="neko-xbps-inspect-") as tmp_name:
        tmp = Path(tmp_name)
        tar_path = prepare_tar(asset_path, asset_name, tmp)
        try:
            archive = tarfile.open(tar_path, mode="r:*")
        except (tarfile.TarError, OSError) as exc:
            raise GeneratorError(f"{asset_name}: tarball corrupto o no soportado: {exc}") from exc

        with archive:
            members = archive.getmembers()
            if not members:
                raise GeneratorError(f"{asset_name}: tarball vacio")
            if len(members) > MAX_MEMBERS:
                raise GeneratorError(f"{asset_name}: demasiadas entradas ({len(members)})")
            unpacked_size = 0
            executable_members: list[tarfile.TarInfo] = []
            license_members: list[tarfile.TarInfo] = []
            regular_paths: list[PurePosixPath] = []
            build_markers: list[str] = []
            for member in members:
                path = safe_member_path(member.name)
                if member.isdev() or member.isfifo():
                    raise GeneratorError(f"entrada especial no permitida: {member.name!r}")
                if member.issym() or member.islnk():
                    validate_link(member)
                if member.isfile():
                    regular_paths.append(path)
                    unpacked_size += member.size
                    if unpacked_size > MAX_UNPACKED_BYTES:
                        raise GeneratorError(f"{asset_name}: contenido descomprimido demasiado grande")
                    if recipe.kind == "binary" and path.name == recipe.executable:
                        executable_members.append(member)
                    if LICENSE_RE.match(path.name):
                        license_members.append(member)
                    if recipe.kind == "source" and source_build_marker(recipe.build_style, path):
                        build_markers.append(path.as_posix())

            license_path: str | None = None
            if license_members:
                license_members.sort(
                    key=lambda item: (len(safe_member_path(item.name).parts), item.name)
                )
                license_path = safe_member_path(license_members[0].name).as_posix()

            if recipe.kind == "source":
                if not build_markers:
                    raise GeneratorError(
                        f"{recipe.pkgname}: no se encontro la estructura de {recipe.build_style}"
                    )
                roots = {path.parts[0] for path in regular_paths if len(path.parts) > 1}
                has_root_files = any(len(path.parts) == 1 for path in regular_paths)
                source_root = next(iter(roots)) if len(roots) == 1 and not has_root_files else None
                marker_paths = [PurePosixPath(path) for path in build_markers]
                if source_root:
                    valid_markers = [
                        path
                        for path in marker_paths
                        if len(path.parts) == 2 and path.parts[0] == source_root
                    ]
                    if license_path:
                        license_parts = PurePosixPath(license_path).parts
                        if license_parts and license_parts[0] == source_root:
                            license_path = PurePosixPath(*license_parts[1:]).as_posix()
                else:
                    valid_markers = [path for path in marker_paths if len(path.parts) == 1]
                if not valid_markers:
                    raise GeneratorError(
                        f"{recipe.pkgname}: {recipe.build_style} solo aparece en un subdirectorio"
                    )
                return InspectedArchive(
                    executable_path=None,
                    license_path=license_path,
                    target_arch="*",
                    source_root=source_root,
                )

            if not executable_members:
                raise GeneratorError(
                    f"{recipe.pkgname}: no se encontro el ejecutable {recipe.executable!r}"
                )
            executable_members.sort(key=lambda item: (len(safe_member_path(item.name).parts), item.name))
            if len(executable_members) > 1:
                first_depth = len(safe_member_path(executable_members[0].name).parts)
                second_depth = len(safe_member_path(executable_members[1].name).parts)
                if first_depth == second_depth:
                    paths = ", ".join(member.name for member in executable_members)
                    raise GeneratorError(
                        f"{recipe.pkgname}: ejecutable ambiguo dentro del tarball: {paths}"
                    )

            executable = executable_members[0]
            extract_root = tmp / "extract"
            extract_root.mkdir()
            try:
                archive.extract(executable, path=extract_root, filter="data")
            except (tarfile.TarError, OSError) as exc:
                raise GeneratorError(f"no se pudo extraer el ejecutable para revisarlo: {exc}") from exc
            executable_path = extract_root / safe_member_path(executable.name)
            inspect_elf(executable_path)

        target_arch = "x86_64-musl" if "musl" in asset_name.lower() else "x86_64"
        return InspectedArchive(
            executable_path=safe_member_path(executable.name).as_posix(),
            license_path=license_path,
            target_arch=target_arch,
        )


def shell_double_quote(value: str, *, preserve_version: bool = False) -> str:
    marker = "__XBPS_VERSION_MARKER__"
    if preserve_version:
        value = value.replace("${version}", marker)
    value = value.replace("\\", "\\\\").replace('"', '\\"').replace("`", "\\`")
    value = value.replace("$", "\\$")
    if preserve_version:
        value = value.replace(marker, "${version}")
    return f'"{value}"'


def versioned_url(url: str, version: str) -> str:
    encoded_version = urllib.parse.quote(version, safe=".+_~-")
    if version in url:
        return url.replace(version, "${version}")
    if encoded_version in url:
        return url.replace(encoded_version, "${version}")
    raise GeneratorError(f"la URL del asset no contiene la version {version!r}: {url}")


def render_template(
    recipe: Recipe,
    version: str,
    homepage: str,
    asset: ReleaseAsset,
    checksum: str,
    inspected: InspectedArchive,
) -> str:
    desc = " ".join(recipe.short_desc.split())
    if len(desc) > 72:
        desc = desc[:69].rstrip() + "..."
    distfiles = versioned_url(asset.url, version)
    lines = [
        f"# Template file for '{recipe.pkgname}'",
        GENERATED_MARKER,
        f"# Source recipe: meta/tarballs.tsv ({recipe.repo})",
        f"pkgname={recipe.pkgname}",
        f"version={version}",
        "revision=1",
    ]
    if recipe.kind == "binary":
        lines.extend(
            [
                f'archs="{inspected.target_arch}"',
                "create_wrksrc=yes",
                "nostrip=yes",
                "nopie=yes",
            ]
        )
    else:
        lines.append(f"build_style={recipe.build_style}")
        if inspected.source_root:
            root = inspected.source_root.replace(version, "${version}")
            lines.append(f"wrksrc={shell_double_quote(root, preserve_version=True)}")
        else:
            lines.append("create_wrksrc=yes")
        if recipe.configure_args:
            lines.append(f"configure_args={shell_double_quote(recipe.configure_args)}")
    if recipe.hostmakedepends:
        lines.append(f"hostmakedepends={shell_double_quote(recipe.hostmakedepends)}")
    if recipe.makedepends:
        lines.append(f"makedepends={shell_double_quote(recipe.makedepends)}")
    if recipe.depends:
        lines.append(f"depends={shell_double_quote(recipe.depends)}")
    lines.extend(
        [
            f"short_desc={shell_double_quote(desc)}",
            f"maintainer={shell_double_quote(recipe.maintainer)}",
            f"license={shell_double_quote(recipe.license)}",
            f"homepage={shell_double_quote(homepage)}",
            f"distfiles={shell_double_quote(distfiles, preserve_version=True)}",
            f"checksum={checksum}",
        ]
    )
    if recipe.kind == "binary":
        if not inspected.executable_path:
            raise GeneratorError(f"{recipe.pkgname}: falta ruta del ejecutable inspeccionado")
        lines.extend(
            [
                "",
                "do_install() {",
                f"\tvbin {shell_double_quote(inspected.executable_path)} {shell_double_quote(recipe.executable)}",
            ]
        )
        if inspected.license_path:
            lines.append(f"\tvlicense {shell_double_quote(inspected.license_path)}")
        lines.append("}")
    elif inspected.license_path:
        lines.extend(
            [
                "",
                "post_install() {",
                f"\tvlicense {shell_double_quote(inspected.license_path)}",
                "}",
            ]
        )
    lines.append("")
    return "\n".join(lines)


def existing_template_status(path: Path, version: str, checksum: str) -> str:
    if not path.exists():
        return "new"
    current = path.read_text(encoding="utf-8")
    if GENERATED_MARKER not in current:
        return "manual"
    old_version_match = re.search(r"^version=(.+)$", current, re.MULTILINE)
    old_checksum_match = re.search(r"^checksum=(\S+)$", current, re.MULTILINE)
    old_version = old_version_match.group(1).strip() if old_version_match else ""
    old_checksum = old_checksum_match.group(1).strip() if old_checksum_match else ""
    if old_version == version and old_checksum and old_checksum != checksum:
        raise GeneratorError(
            f"{path.parent.name}: el asset de la misma version cambio de checksum; revision manual requerida"
        )
    return "generated"


def process_recipe(recipe: Recipe, args: argparse.Namespace, token: str) -> str:
    log(f"Procesando {recipe.pkgname} ({recipe.repo})...")
    version, homepage, asset = latest_release(recipe, token)
    log(f"  asset: {asset.name}")
    with tempfile.TemporaryDirectory(prefix=f"neko-xbps-{recipe.pkgname}-") as tmp_name:
        asset_path = Path(tmp_name) / asset.name
        checksum = download_asset(asset, asset_path)
        inspected = inspect_archive(asset_path, asset.name, recipe)
    rendered = render_template(
        recipe, version, homepage, asset, checksum, inspected
    )
    template_path = ROOT / recipe.pkgname / "template"
    status = existing_template_status(template_path, version, checksum)
    if status == "manual":
        raise GeneratorError(
            f"{recipe.pkgname}: existe un template manual; no se sobrescribira"
        )
    if args.check:
        if not template_path.exists() or template_path.read_text(encoding="utf-8") != rendered:
            raise GeneratorError(f"{recipe.pkgname}: template desactualizado")
        log("  correcto")
        return "unchanged"
    if args.dry_run:
        log(f"  generaria {template_path.relative_to(ROOT)} para {version}")
        return "dry-run"
    template_path.parent.mkdir(parents=True, exist_ok=True)
    if template_path.exists() and template_path.read_text(encoding="utf-8") == rendered:
        log("  sin cambios")
        return "unchanged"
    template_path.write_text(rendered, encoding="utf-8")
    log(f"  escrito: {template_path.relative_to(ROOT)}")
    return "updated"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("packages", nargs="*", help="pkgname concretos; por defecto procesa todos")
    parser.add_argument("--recipes", type=Path, default=DEFAULT_RECIPES)
    parser.add_argument("--check", action="store_true", help="no escribe y falla si hay cambios")
    parser.add_argument("--dry-run", action="store_true", help="muestra cambios sin escribir")
    parser.add_argument(
        "--allow-failures",
        action="store_true",
        help="continua y retorna exito aunque alguna receta falle",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        recipes = read_recipes(args.recipes)
    except (OSError, GeneratorError) as exc:
        log(f"Error: {exc}")
        return 2
    if args.packages:
        requested = set(args.packages)
        available = {recipe.pkgname for recipe in recipes}
        missing = sorted(requested - available)
        if missing:
            log(f"Error: paquetes sin receta: {', '.join(missing)}")
            return 2
        recipes = [recipe for recipe in recipes if recipe.pkgname in requested]
    if not recipes:
        log("No hay recetas seleccionadas.")
        return 0

    token = os.environ.get("GITHUB_TOKEN", "")
    failures: list[str] = []
    updated = 0
    for recipe in recipes:
        try:
            result = process_recipe(recipe, args, token)
            if result == "updated":
                updated += 1
        except (GeneratorError, OSError) as exc:
            message = f"{recipe.pkgname}: {exc}"
            failures.append(message)
            log(f"  ERROR: {exc}")

    log(f"Completado: {updated} template(s) actualizado(s), {len(failures)} fallo(s).")
    if failures:
        summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
        if summary_path:
            with Path(summary_path).open("a", encoding="utf-8") as summary:
                summary.write("## Fallos del generador de templates\n\n")
                for failure in failures:
                    summary.write(f"- `{failure}`\n")
        if not args.allow_failures:
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

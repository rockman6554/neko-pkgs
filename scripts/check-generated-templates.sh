#!/bin/sh
set -eu

repo_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
status=0
template_list=$(mktemp)
trap 'rm -f "$template_list"' EXIT INT TERM HUP

find "$repo_root" -mindepth 2 -maxdepth 2 -name template -type f | sort > "$template_list"
while IFS= read -r template; do
    if grep -Fq '# Generated by scripts/generate-xbps-templates.py; DO NOT EDIT.' "$template"; then
        if ! bash -n "$template"; then
            status=1
        fi
        pkg_dir=$(basename "$(dirname "$template")")
        pkg_name=$(sed -n 's/^pkgname=//p' "$template" | head -n 1)
        if [ "$pkg_dir" != "$pkg_name" ]; then
            printf 'ERROR: %s: directorio y pkgname no coinciden\n' "$template" >&2
            status=1
        fi
    fi
done < "$template_list"

exit "$status"
